#[derive(Default)]
pub(super) struct CountingKms(pub(super) AtomicUsize);

#[async_trait]
impl kms::KmsService for CountingKms {
    async fn generate_key(
        &self,
        _: &kms::RequestContext,
        scope: kms::KeyScope,
    ) -> kms::Result<(kms::EncryptionCid, [u8; 32])> {
        assert!(matches!(scope, kms::KeyScope::Document { .. }));
        let count = self.0.fetch_add(1, Ordering::SeqCst) + 1;
        let key = [u8::try_from(count).unwrap(); 32];
        let block = defra_core::Encryption { key: key.to_vec() };
        let cid =
            defra_core::block::generate_cid_from_bytes(&block.to_dag_cbor().unwrap()).unwrap();
        Ok((cid, key))
    }

    async fn get_keys(
        &self,
        _: &kms::RequestContext,
        cids: &[kms::EncryptionCid],
    ) -> kms::Result<kms::KeyResults> {
        let (results, sender) = kms::KeyResults::new(cids.len());
        for cid in cids {
            let mut found = None;
            for count in 1..=self.0.load(Ordering::SeqCst) {
                let key = [u8::try_from(count).unwrap(); 32];
                let block = defra_core::Encryption { key: key.to_vec() };
                if defra_core::block::generate_cid_from_bytes(&block.to_dag_cbor().unwrap())
                    .unwrap()
                    == *cid
                {
                    found = Some(key);
                    break;
                }
            }
            sender
                .send(Ok((*cid, found.expect("key was generated by this KMS"))))
                .await
                .unwrap();
        }
        drop(sender);
        Ok(results)
    }

    async fn serve_request(
        &self,
        _: kms::PeerIdentity,
        _: kms::FetchEncryptionKeyRequest,
    ) -> kms::Result<kms::FetchEncryptionKeyReply> {
        Err(kms::Error::Unsupported("unexpected peer request"))
    }
}

pub(super) struct Fixture {
    pub(super) db: Arc<DB<RegolithStore>>,
    pub(super) kms: Arc<CountingKms>,
}

pub(super) async fn fixture() -> Fixture {
    let db = Arc::new(DB::new(RegolithStore::in_memory().unwrap()).unwrap());
    let kms = Arc::new(CountingKms::default());
    db.set_kms(kms.clone());
    db.create_collection(CollectionVersion::new(
        "Secrets",
        "secrets-v1",
        "col-secrets",
        vec![
            FieldDescription::new("1", "_docID", FieldKind::doc_id()),
            FieldDescription::new("2", "left", FieldKind::string()),
            FieldDescription::new("3", "right", FieldKind::string()),
            FieldDescription::new("4", "public", FieldKind::string()),
        ],
    ))
    .await
    .unwrap();
    Fixture { db, kms }
}

/// A request that encrypts the `left` and `right` fields.
fn encrypted() -> RequestContext {
    RequestContext::default().with_encryption(Some(EncryptionConfig {
        encrypt_doc: false,
        encrypt_fields: vec!["left".to_string(), "right".to_string()],
    }))
}

fn document(value: &str) -> Document {
    let mut doc = Document::new();
    doc.set("left", value);
    doc.set("right", value);
    doc.set("public", value);
    doc
}

struct CountingRemoteSigner {
    key: crypto::Ed25519PrivateKey,
    calls: AtomicUsize,
}

/// A remote signer over a fresh Ed25519 key that counts its calls, and the
/// signing configuration that delegates to it.
fn remote_signer() -> (
    Arc<CountingRemoteSigner>,
    defra_core::signing::SigningConfig,
) {
    let key = crypto::generate_ed25519().unwrap();
    let public = key.public_key();
    let public_key_bytes = public.raw_owned();
    let public_key_hex = hex::encode(public.raw());
    let signer = Arc::new(CountingRemoteSigner {
        key,
        calls: AtomicUsize::new(0),
    });
    let signing = defra_core::signing::SigningConfig {
        key_type: defra_core::signing::SigningKeyType::Ed25519,
        private_key_bytes: Vec::new(),
        public_key_bytes,
        public_key_hex,
        remote_signer: Some(signer.clone()),
        signing_authorization: None,
    };
    (signer, signing)
}

impl defra_core::signing::RemoteSigner for CountingRemoteSigner {
    fn sign_sync(
        &self,
        data: &[u8],
        _authorization: Option<&defra_core::signing::SigningAuthorization>,
    ) -> Result<Vec<u8>, String> {
        self.calls.fetch_add(1, Ordering::SeqCst);
        self.key
            .sign(data)
            .map_err(|error| format!("remote signing failed: {error}"))
    }
}

#[tokio::test]
async fn direct_create_resolves_kms_and_signature_inputs_once() {
    let fixture = fixture().await;
    let (signer, signing) = remote_signer();

    let result = AutoCommitMutator::new(Arc::clone(&fixture.db))
        .create(
            &encrypted().with_signing(Some(signing)),
            "Secrets",
            document("direct"),
        )
        .await;
    result.unwrap();

    assert_eq!(fixture.kms.0.load(Ordering::SeqCst), 2);
    assert_eq!(signer.calls.load(Ordering::SeqCst), 4);
}

#[tokio::test]
async fn direct_delete_many_resolves_each_signature_once() {
    let fixture = fixture().await;
    let mutator = AutoCommitMutator::new(Arc::clone(&fixture.db));
    let first = mutator
        .create(
            &defra_core::RequestContext::default(),
            "Secrets",
            document("first"),
        )
        .await
        .unwrap();
    let second = mutator
        .create(
            &defra_core::RequestContext::default(),
            "Secrets",
            document("second"),
        )
        .await
        .unwrap();
    let (signer, signing) = remote_signer();

    let result = mutator
        .delete_many_impl(
            &RequestContext::default().with_signing(Some(signing)),
            "Secrets",
            &[first.doc_id, second.doc_id],
        )
        .await;
    let results = result.unwrap();
    assert!(results.iter().all(|result| result.existed));
    assert_eq!(signer.calls.load(Ordering::SeqCst), 2);
}

